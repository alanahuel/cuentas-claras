import { test, expect } from '@playwright/test';
test('visible signup and protected account deletion', async ({page}) => {
 await page.goto('/');
 await expect(page.getByRole('button',{name:'Crear una cuenta',exact:true})).toBeVisible();
 await page.screenshot({path:'../.impeccable/review/access-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'../.impeccable/review/access-mobile.png',fullPage:true});
 await page.goto('/?registro=1');
 await page.getByLabel('Tu nombre',{exact:true}).fill('Prueba eliminación');
 await page.getByLabel('Correo electrónico',{exact:true}).fill(`delete-${Date.now()}@example.test`);
 await page.getByLabel('Contraseña',{exact:true}).fill('registration-local-test');
 await page.getByLabel('Repite la contraseña',{exact:true}).fill('registration-local-test');
 await page.getByRole('button',{name:'Crear cuenta',exact:true}).click();
 await page.getByRole('button',{name:'Opciones de mi cuenta',exact:true}).click();
 await page.getByRole('button',{name:'Editar perfil',exact:true}).click();
 await page.getByRole('button',{name:'Eliminar mi cuenta',exact:true}).click();
 await expect(page.getByRole('button',{name:'Eliminar cuenta definitivamente',exact:true})).toBeDisabled();
 await page.getByLabel('Contraseña para eliminar la cuenta',{exact:true}).fill('wrong-password');
 await page.getByLabel('Escribe ELIMINAR para confirmar',{exact:true}).fill('ELIMINAR');
 await page.getByRole('button',{name:'Eliminar cuenta definitivamente',exact:true}).click();
 await expect(page.getByText('La contraseña actual no es correcta.',{exact:true})).toBeVisible();
 await page.getByLabel('Contraseña para eliminar la cuenta',{exact:true}).fill('registration-local-test');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.locator('.delete-account').screenshot({path:'../.impeccable/review/delete-mobile.png'});
 page.on('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Eliminar cuenta definitivamente',exact:true}).click();
 await expect(page.getByLabel('Repite la contraseña',{exact:true})).toBeVisible();
 const me=await page.request.get('/api/me'); expect(me.status()).toBe(401);
});
